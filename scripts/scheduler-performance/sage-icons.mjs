export function icon(name) {
  const rows = glyphs[name];
  if (!rows) throw Error("Unknown Sage glyph: " + name);
  return `<svg class="sage-icon" viewBox="0 0 7 7" aria-hidden="true" focusable="false" fill="currentColor">${rows.flatMap((row, y) => [...row].flatMap((v, x) => v === "1" ? `<circle cx="${x + .5}" cy="${y + .5}" r=".48"/>` : [])).join("")}</svg>`;
}
